-- ====================================================================
-- BASE DE DATOS: BD_TRANSPORTE
-- Sistema de Rutas de Leche, Control de Mermas y Liquidación Multimoneda
-- Estándar de Nomenclatura SQL Server: TB_*
-- ====================================================================

IF NOT EXISTS (SELECT name FROM sys.databases WHERE name = 'BD_TRANSPORTE')
BEGIN
    CREATE DATABASE BD_TRANSPORTE;
END
GO

USE BD_TRANSPORTE;
GO

-- 1. ROLES Y SEGURIDAD
IF OBJECT_ID('dbo.TB_ROLES', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.TB_ROLES (
        Id INT IDENTITY(1,1) PRIMARY KEY,
        Codigo NVARCHAR(30) NOT NULL UNIQUE,
        Nombre NVARCHAR(100) NOT NULL,
        Descripcion NVARCHAR(250) NULL,
        Activo BIT NOT NULL DEFAULT 1,
        CreatedAt DATETIME2 NOT NULL DEFAULT GETDATE()
    );
END
GO

-- 2. USUARIOS (UNIFICA ADMINS, CHOFERES Y RECEPTORÍAS)
IF OBJECT_ID('dbo.TB_USUARIOS', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.TB_USUARIOS (
        Id INT IDENTITY(1,1) PRIMARY KEY,
        Username NVARCHAR(50) NOT NULL UNIQUE,
        PasswordHash NVARCHAR(255) NOT NULL,
        NombreCompleto NVARCHAR(100) NOT NULL,
        Cedula NVARCHAR(20) NULL,
        Telefono NVARCHAR(30) NULL,
        VehiculoPlaca NVARCHAR(20) NULL,
        CapacidadTanqueLitros INT NULL,
        Rol NVARCHAR(30) NOT NULL DEFAULT 'CHOFER',
        RolId INT NULL FOREIGN KEY REFERENCES dbo.TB_ROLES(Id),
        Activo BIT NOT NULL DEFAULT 1,
        IsDeleted BIT NOT NULL DEFAULT 0,
        CreatedAt DATETIME2 NOT NULL DEFAULT GETDATE()
    );
END
GO

-- 3. MÓDULOS DEL SISTEMA
IF OBJECT_ID('dbo.TB_MODULOS', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.TB_MODULOS (
        Id INT IDENTITY(1,1) PRIMARY KEY,
        Codigo NVARCHAR(50) NOT NULL UNIQUE,
        Nombre NVARCHAR(100) NOT NULL,
        Icono NVARCHAR(50) NULL,
        Orden INT NOT NULL DEFAULT 0,
        Activo BIT NOT NULL DEFAULT 1
    );
END
GO

-- 4. PERMISOS ATÓMICOS
IF OBJECT_ID('dbo.TB_PERMISOS', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.TB_PERMISOS (
        Id INT IDENTITY(1,1) PRIMARY KEY,
        ModuloId INT NOT NULL FOREIGN KEY REFERENCES dbo.TB_MODULOS(Id),
        Codigo NVARCHAR(100) NOT NULL UNIQUE,
        Nombre NVARCHAR(150) NOT NULL,
        Accion NVARCHAR(30) NOT NULL, -- 'VER', 'CREAR', 'EDITAR', 'ELIMINAR', 'APROBAR', 'EXPORTAR'
        Descripcion NVARCHAR(250) NULL,
        Activo BIT NOT NULL DEFAULT 1
    );
END
GO

-- 5. MATRIZ ROL-PERMISOS
IF OBJECT_ID('dbo.TB_ROL_PERMISOS', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.TB_ROL_PERMISOS (
        Id INT IDENTITY(1,1) PRIMARY KEY,
        RolId INT NOT NULL FOREIGN KEY REFERENCES dbo.TB_ROLES(Id) ON DELETE CASCADE,
        PermisoId INT NOT NULL FOREIGN KEY REFERENCES dbo.TB_PERMISOS(Id) ON DELETE CASCADE,
        Concedido BIT NOT NULL DEFAULT 1,
        CreatedAt DATETIME2 NOT NULL DEFAULT GETDATE(),
        CONSTRAINT UQ_Rol_Permiso UNIQUE (RolId, PermisoId)
    );
END
GO

-- 6. HISTORIAL BCV (TASAS DIARIAS USD -> BS)
IF OBJECT_ID('dbo.TB_HISTORIAL_BCV', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.TB_HISTORIAL_BCV (
        Id INT IDENTITY(1,1) PRIMARY KEY,
        Fecha DATE NOT NULL UNIQUE,
        TasaDolarBs DECIMAL(18,4) NOT NULL,
        Fuente NVARCHAR(50) DEFAULT 'BCV',
        Observacion NVARCHAR(200) NULL,
        CreatedAt DATETIME2 NOT NULL DEFAULT GETDATE(),
        CreatedBy INT NULL FOREIGN KEY REFERENCES dbo.TB_USUARIOS(Id)
    );
END
GO

-- 7. TIPOS DE SERVICIO (RUTA PROPIA VS TRANSPORTE/FLETE)
IF OBJECT_ID('dbo.TB_TIPO_SERVICIO', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.TB_TIPO_SERVICIO (
        Id INT IDENTITY(1,1) PRIMARY KEY,
        Nombre NVARCHAR(50) NOT NULL,
        Descripcion NVARCHAR(250) NULL,
        Activo BIT NOT NULL DEFAULT 1
    );
END
GO

-- 8. BANCOS
IF OBJECT_ID('dbo.TB_BANCOS', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.TB_BANCOS (
        Id INT IDENTITY(1,1) PRIMARY KEY,
        Codigo NVARCHAR(10) NOT NULL UNIQUE,
        Nombre NVARCHAR(100) NOT NULL,
        Activo BIT NOT NULL DEFAULT 1
    );
END
GO

-- 9. FINCAS
IF OBJECT_ID('dbo.TB_FINCAS', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.TB_FINCAS (
        Id INT IDENTITY(1,1) PRIMARY KEY,
        Codigo NVARCHAR(20) NULL UNIQUE,
        Nombre NVARCHAR(100) NOT NULL,
        Propietario NVARCHAR(100) NOT NULL,
        CedulaRIF NVARCHAR(20) NULL,
        Telefono NVARCHAR(30) NULL,
        BancoId INT NULL FOREIGN KEY REFERENCES dbo.TB_BANCOS(Id),
        NumeroCuenta NVARCHAR(20) NULL,
        TipoServicioId INT NULL FOREIGN KEY REFERENCES dbo.TB_TIPO_SERVICIO(Id),
        PrecioLitroUSD DECIMAL(10,4) NOT NULL DEFAULT 0.0000,
        Activo BIT NOT NULL DEFAULT 1,
        IsDeleted BIT NOT NULL DEFAULT 0,
        CreatedAt DATETIME2 NOT NULL DEFAULT GETDATE()
    );
END
GO

-- 10. COMPAÑÍAS / PLANTAS / QUESERAS RECEPTORAS
IF OBJECT_ID('dbo.TB_COMPANIAS', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.TB_COMPANIAS (
        Id INT IDENTITY(1,1) PRIMARY KEY,
        Nombre NVARCHAR(100) NOT NULL,
        Encargado NVARCHAR(100) NULL,
        Telefono NVARCHAR(30) NULL,
        Direccion NVARCHAR(200) NULL,
        TipoServicioId INT NULL FOREIGN KEY REFERENCES dbo.TB_TIPO_SERVICIO(Id),
        PrecioCompraLitroUSD DECIMAL(10,4) NOT NULL DEFAULT 0.0000,
        Activo BIT NOT NULL DEFAULT 1,
        IsDeleted BIT NOT NULL DEFAULT 0,
        CreatedAt DATETIME2 NOT NULL DEFAULT GETDATE()
    );
END
GO

-- 11. CICLOS OPERATIVOS (EJ. MIÉRCOLES A MARTES)
IF OBJECT_ID('dbo.TB_CICLOS_OPERATIVOS', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.TB_CICLOS_OPERATIVOS (
        Id INT IDENTITY(1,1) PRIMARY KEY,
        Codigo NVARCHAR(30) NOT NULL UNIQUE,
        FechaInicio DATE NOT NULL,
        FechaFin DATE NOT NULL,
        Estado NVARCHAR(20) NOT NULL DEFAULT 'ABIERTO',
        FechaCierre DATETIME2 NULL,
        CerradoPor INT NULL FOREIGN KEY REFERENCES dbo.TB_USUARIOS(Id),
        Observaciones NVARCHAR(500) NULL,
        CreatedAt DATETIME2 NOT NULL DEFAULT GETDATE()
    );
END
GO

-- 12. RUTAS DE RECOLECCIÓN
IF OBJECT_ID('dbo.TB_RUTAS_RECOLECCION', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.TB_RUTAS_RECOLECCION (
        Id BIGINT IDENTITY(1,1) PRIMARY KEY,
        CicloId INT NOT NULL FOREIGN KEY REFERENCES dbo.TB_CICLOS_OPERATIVOS(Id),
        Fecha DATE NOT NULL,
        FincaId INT NOT NULL FOREIGN KEY REFERENCES dbo.TB_FINCAS(Id),
        UsuarioId INT NOT NULL FOREIGN KEY REFERENCES dbo.TB_USUARIOS(Id),
        Litros INT NOT NULL,
        PrecioLitroUSDAplicado DECIMAL(10,4) NOT NULL,
        TasaDolarBsAplicada DECIMAL(18,4) NOT NULL,
        SubtotalUSD AS (Litros * PrecioLitroUSDAplicado) PERSISTED,
        SubtotalBs AS ((Litros * PrecioLitroUSDAplicado) * TasaDolarBsAplicada) PERSISTED,
        Observacion NVARCHAR(500) NULL,
        UuidLocal VARCHAR(50) NULL,
        CreatedAt DATETIME2 NOT NULL DEFAULT GETDATE(),
        CreatedBy INT NULL FOREIGN KEY REFERENCES dbo.TB_USUARIOS(Id),
        ModifiedAt DATETIME2 NULL,
        ModifiedBy INT NULL FOREIGN KEY REFERENCES dbo.TB_USUARIOS(Id)
    );
END
GO

-- 13. ENTREGAS A COMPAÑÍAS
IF OBJECT_ID('dbo.TB_ENTREGAS_COMPANIA', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.TB_ENTREGAS_COMPANIA (
        Id BIGINT IDENTITY(1,1) PRIMARY KEY,
        CicloId INT NOT NULL FOREIGN KEY REFERENCES dbo.TB_CICLOS_OPERATIVOS(Id),
        Fecha DATE NOT NULL,
        CompaniaId INT NOT NULL FOREIGN KEY REFERENCES dbo.TB_COMPANIAS(Id),
        UsuarioId INT NOT NULL FOREIGN KEY REFERENCES dbo.TB_USUARIOS(Id),
        Litros INT NOT NULL,
        PrecioVentaUSD DECIMAL(10,4) NOT NULL DEFAULT 0.0000,
        TasaDolarBsAplicada DECIMAL(18,4) NOT NULL,
        SubtotalUSD AS (Litros * PrecioVentaUSD) PERSISTED,
        SubtotalBs AS ((Litros * PrecioVentaUSD) * TasaDolarBsAplicada) PERSISTED,
        Observacion NVARCHAR(500) NULL,
        CreatedAt DATETIME2 NOT NULL DEFAULT GETDATE(),
        CreatedBy INT NULL FOREIGN KEY REFERENCES dbo.TB_USUARIOS(Id),
        ModifiedAt DATETIME2 NULL,
        ModifiedBy INT NULL FOREIGN KEY REFERENCES dbo.TB_USUARIOS(Id)
    );
END
GO

-- 14. ADELANTOS BIMONEDA
IF OBJECT_ID('dbo.TB_ADELANTOS', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.TB_ADELANTOS (
        Id INT IDENTITY(1,1) PRIMARY KEY,
        TipoBeneficiario NVARCHAR(20) NOT NULL,
        BeneficiarioId INT NOT NULL,
        Fecha DATE NOT NULL,
        Moneda NVARCHAR(10) NOT NULL DEFAULT 'BS',
        MontoOriginal DECIMAL(18,2) NOT NULL,
        TasaCambioFecha DECIMAL(18,4) NOT NULL DEFAULT 1.0000,
        MontoEnBs AS (CASE WHEN Moneda = 'USD' THEN MontoOriginal * TasaCambioFecha ELSE MontoOriginal END) PERSISTED,
        Observacion NVARCHAR(500) NULL,
        Estado NVARCHAR(20) NOT NULL DEFAULT 'PENDIENTE',
        CicloLiquidadoId INT NULL FOREIGN KEY REFERENCES dbo.TB_CICLOS_OPERATIVOS(Id),
        CreatedAt DATETIME2 NOT NULL DEFAULT GETDATE(),
        CreatedBy INT NULL FOREIGN KEY REFERENCES dbo.TB_USUARIOS(Id)
    );
END
GO

-- 15. LIQUIDACIONES CABECERA
IF OBJECT_ID('dbo.TB_LIQUIDACIONES_CABECERA', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.TB_LIQUIDACIONES_CABECERA (
        Id INT IDENTITY(1,1) PRIMARY KEY,
        CicloId INT NOT NULL UNIQUE FOREIGN KEY REFERENCES dbo.TB_CICLOS_OPERATIVOS(Id),
        FechaLiquidacion DATETIME2 NOT NULL DEFAULT GETDATE(),
        TotalLitrosGeneral INT NOT NULL,
        TotalMontoUSD DECIMAL(18,2) NOT NULL,
        TotalBrutoBs DECIMAL(18,2) NOT NULL,
        TotalAdelantosBs DECIMAL(18,2) NOT NULL,
        TotalNetoAPagarBs DECIMAL(18,2) NOT NULL,
        ProcesadoPor INT NOT NULL FOREIGN KEY REFERENCES dbo.TB_USUARIOS(Id),
        Estado NVARCHAR(20) NOT NULL DEFAULT 'APROBADA'
    );
END
GO

-- 16. LIQUIDACIONES DETALLE FINCA
IF OBJECT_ID('dbo.TB_LIQUIDACIONES_DETALLE_FINCA', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.TB_LIQUIDACIONES_DETALLE_FINCA (
        Id BIGINT IDENTITY(1,1) PRIMARY KEY,
        LiquidacionId INT NOT NULL FOREIGN KEY REFERENCES dbo.TB_LIQUIDACIONES_CABECERA(Id),
        FincaId INT NOT NULL FOREIGN KEY REFERENCES dbo.TB_FINCAS(Id),
        TotalLitros INT NOT NULL,
        TotalMontoUSD DECIMAL(18,2) NOT NULL,
        TotalBrutoBs DECIMAL(18,2) NOT NULL,
        TotalAdelantosBs DECIMAL(18,2) NOT NULL,
        NetoPagarBs DECIMAL(18,2) NOT NULL,
        BancoNombre NVARCHAR(100) NULL,
        NumeroCuenta NVARCHAR(20) NULL,
        EstadoPago NVARCHAR(20) NOT NULL DEFAULT 'PENDIENTE_TRANSFERENCIA'
    );
END
GO
